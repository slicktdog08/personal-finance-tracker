export type IconName = keyof typeof ICONS;

export interface IconProps {
  name: IconName;
  /** 14 meta · 16 buttons · 18 default · 20–26 nav/tab bar. */
  size?: number;
  strokeWidth?: number;
  /** Accessible name; omit for decorative icons (the default). */
  label?: string;
  className?: string;
  style?: React.CSSProperties;
}

export function Icon({ name, size = 18, strokeWidth = 1.8, label, className = "", style }: IconProps) {
  const Cmp = ICONS[name];
  return (
    <Cmp
      className={"mp-icon " + className}
      size={size}
      strokeWidth={strokeWidth}
      style={style}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
    />
  );
}
